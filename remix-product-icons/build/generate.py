defs, missing_remix, missing_codicon = {}, [], []
for cid, candidates in M.items():
    name = next((c for c in candidates if c in remix), None)
    if not name:
        missing_remix.append((cid, candidates)); continue
    # codicon-only IDs must exist in the codicon set; *-icon IDs are workbench-registered
    if cid not in codicons and not cid.endswith("-icon"):
        missing_codicon.append(cid)
    defs[cid] = {"fontCharacter": "\\" + remix[name]}

theme = {
    "fonts": [{"id": "remixicon", "src": [{"path": "./remixicon.woff", "format": "woff"}],
               "weight": "normal", "style": "normal"}],
    "iconDefinitions": defs,
}
out = HERE.parent / "theme" / "remix-product-icons.json"
out.write_text(json.dumps(theme, indent=2))
print(f"mapped {len(defs)}")
print("missing remix:", missing_remix)
print("unknown codicon:", missing_codicon)
