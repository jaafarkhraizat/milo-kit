#!/usr/bin/env node
// Maintainer only. Rebuilds settings.jsonc from your live VS Code settings.json, keeping comments.
// Usage: node scripts/sync-from-live.js [path/to/settings.json] [--initials JK]
// Drops personal keys, swaps your initials for {{INITIALS}}, and makes the tab icon path portable.

const fs = require('fs');
const path = require('path');
const os = require('os');
const jsonc = require('../lib/vendor/jsonc-parser/main.js');

const args = process.argv.slice(2);
const flag = (name) => { const i = args.indexOf(name); return i >= 0 ? args.splice(i, 2)[1] : null; };
const initials = flag('--initials') || 'JK';
const live = args[0] || path.join(os.homedir(), 'Library/Application Support/Code/User/settings.json');
const out = path.join(__dirname, '..', 'settings.jsonc');

// Keys in the live file that are personal, not part of the theme.
const PERSONAL = [
  'editor.defaultFormatter', 'editor.formatOnSave', 'git.autofetch', 'git.enableSmartCommit',
  'claudeCode.hideOnboarding', 'claudeCode.enableNewConversationShortcut', 'editor.largeFileOptimizations',
  'editor.accessibilityPageSize', 'http.systemCertificatesNode', 'security.workspace.trust.untrustedFiles',
];

let text = fs.readFileSync(live, 'utf8');

for (const key of PERSONAL) {
  const before = text;
  text = text.replace(new RegExp(`^[ \\t]*"${key.replace(/\./g, '\\.')}":[^\\n]*\\n`, 'm'), '');
  if (text === before) console.warn(`note: ${key} not found (fine if you removed it)`);
}
text = text.replace(/\/\/ ── Existing prefs \(kept\) ─+/, '// ── Theme stack ───────────────────────────────────────');

const avatar = `"'${initials}'"`;
const avatarCount = text.split(avatar).length - 1;
text = text.split(avatar).join(`"'{{INITIALS}}'"`);

// Tab icons: <extensions>/anthropic.claude-code-*/resources/../../../claude-tab-icons/ = <editor home>/claude-tab-icons/
text = text.replace(/(\\")[^"\\]*claude-tab-icons\//g, '$1../../../claude-tab-icons/');

const header = [
  '// Milo Kit: VS Code settings fragment. Generated by scripts/sync-from-live.js. Do not edit by hand.',
  '// install.sh merges this into the user\'s settings.json. {{INITIALS}} becomes the user\'s avatar initials.',
  '',
].join('\n');
text = header + text.replace(/^\uFEFF/, '');

const errors = [];
const parsed = jsonc.parse(text, errors, { allowTrailingComma: true });
if (errors.length) { console.error('parse errors:', errors.slice(0, 5)); process.exit(1); }
if (text.includes(`'${initials}'`)) { console.error(`initials '${initials}' still present`); process.exit(1); }
if (/Library\/Application Support/.test(text)) { console.error('machine-specific path still present'); process.exit(1); }

fs.writeFileSync(out, text);
console.log(`wrote ${path.relative(process.cwd(), out)}: ${Object.keys(parsed).length} keys, ${avatarCount} avatar(s) templated`);
